#!/bin/bash
## 把 git 信息固化成头文件 version_git.h
## 目的：远程调试/交叉编译时源码目录若没有 .git（同步、拷贝过去的目录），也能编出带分支和 commit 的二进制
## 输出：stdout 只打印 GIT_BRANCH/GIT_COMMIT/GIT_COMMIT_TIME（供 CMake 或构建脚本解析），提示信息走 stderr
set -e
SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
PRJ_DIR=$(cd "$SCRIPT_DIR/.." && pwd)
OUT="$PRJ_DIR/version_git.h"

# 统一走这里调用 git：safe.directory 规避 git 2.35.2+ 的 "detected dubious ownership"（挂载/同步目录常见）
git_cmd() {
	git -c safe.directory="$PRJ_DIR" -C "$PRJ_DIR" "$@"
}

branch_name=$(git_cmd rev-parse --abbrev-ref HEAD 2>/dev/null || true)
commit_id=$(git_cmd rev-parse --short HEAD 2>/dev/null || true)
commit_time=$(git_cmd log -1 --format=%cI 2>/dev/null || true)
if [ -n "$commit_id" ] && ! git_cmd diff --quiet --ignore-submodules HEAD 2>/dev/null; then
	commit_id="${commit_id}-dirty"
fi

# 取不到 git 信息时保留已有文件（远程机器无 .git，使用随源码同步过来的版本），并从已有文件恢复值
if [ -z "$branch_name" ] || [ -z "$commit_id" ]; then
	if [ -f "$OUT" ]; then
		echo "未获取到 git 信息，保留已有的 $OUT" >&2
		branch_name=$(sed -n 's/^#define GIT_BRANCH "\(.*\)"$/\1/p' "$OUT" | head -1)
		commit_id=$(sed -n 's/^#define GIT_COMMIT "\(.*\)"$/\1/p' "$OUT" | head -1)
		commit_time=$(sed -n 's/^#define GIT_COMMIT_TIME "\(.*\)"$/\1/p' "$OUT" | head -1)
		printf 'GIT_BRANCH=%s\nGIT_COMMIT=%s\nGIT_COMMIT_TIME=%s\n' "${branch_name:-unknown}" "${commit_id:-unknown}" "${commit_time:-unknown}"
		exit 0
	fi
	branch_name=${branch_name:-unknown}
	commit_id=${commit_id:-unknown}
	commit_time=${commit_time:-unknown}
fi

NEW_CONTENT=$(cat <<EOF
// Code generated by scripts/gen_version.sh. DO NOT EDIT.
// 由 scripts/gen_version.sh 固化的 git 信息。
// 用途：远程调试/交叉编译时源码目录没有 .git，靠本文件提供分支与 commit。
#ifndef VERSION_GIT_H
#define VERSION_GIT_H

#define GIT_BRANCH "$branch_name"
#define GIT_COMMIT "$commit_id"
#define GIT_COMMIT_TIME "$commit_time"

#endif // VERSION_GIT_H
EOF
)

# 内容无变化时不写文件，避免产生无意义的重编译
if [ -f "$OUT" ] && [ "$NEW_CONTENT" = "$(cat "$OUT")" ]; then
	echo "git 信息无变化：$branch_name $commit_id" >&2
else
	echo "$NEW_CONTENT" > "$OUT"
	echo "已写入 $OUT：$branch_name $commit_id" >&2
fi

printf 'GIT_BRANCH=%s\nGIT_COMMIT=%s\nGIT_COMMIT_TIME=%s\n' "$branch_name" "$commit_id" "$commit_time"
